<#
.SYNOPSIS
  Copies OpcenterEXCR DLL to Approved, creates OpcenterEXCR folder, and copies config.txt.
  (PDB handling removed as requested.)

.DESCRIPTION
  1) Copies:
        - OpcenterRDnL.Customization.OpcenterEXCR.dll
     to: C:\Users\Public\OpcenterRDnL\DynamicLibraries\Approved
  2) Ensures: C:\Users\Public\OpcenterRDnL\OpcenterEXCR exists
  3) Copies config.txt into that folder.
  4) Logs to: C:\ProgramData\OpcenterRDnL\OpcenterEXCR\Logs.txt

.PARAMETER DllSource
  Path to OpcenterRDnL.Customization.OpcenterEXCR.dll (default: .\OpcenterRDnL.Customization.OpcenterEXCR.dll)

.PARAMETER ConfigSource
  Path to config.txt (default: .\config.txt)

.NOTES
  Uses Copy-Item -Force (overwrites if target exists).
  Add -WhatIf to simulate, or remove -Force to prevent overwrite.
#>

[CmdletBinding()]
param(
    [string]$DllSource     = ".\files\OpcenterRDnL.Customization.OpcenterEXCR.dll",
    [string]$ConfigSource  = ".\files\config.txt"
)

$ErrorActionPreference = 'Stop'

# --- Fixed destinations ---
$ApprovedFolder     = "C:\Users\Public\OpcenterRDnL\DynamicLibraries\Approved"
$OpcenterExcrFolder = "C:\Users\Public\OpcenterRDnL\OpcenterEXCR"

# --- Logging (appends to Logs.txt) ---
$LogDir  = "C:\Users\Public\OpcenterRDnL\OpcenterEXCR"
$LogFile = Join-Path $LogDir "logs.txt"
if (-not (Test-Path -LiteralPath $LogDir -PathType Container)) {
    New-Item -ItemType Directory -Path $LogDir -Force | Out-Null
}
Start-Transcript -Path $LogFile -Append | Out-Null

function Ensure-Folder {
    param([Parameter(Mandatory)][string]$Path)
    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        Write-Verbose "Creating folder: $Path"
        New-Item -ItemType Directory -Path $Path -Force | Out-Null
    }
}

try {
    Write-Host "=== Deploy OpcenterEXCR (COPY mode; PDB excluded) ===" -ForegroundColor Cyan
    Write-Verbose "Parameters:"
    Write-Verbose "  DllSource    = $DllSource"
    Write-Verbose "  ConfigSource = $ConfigSource"

    # Validate sources
    foreach ($src in @($DllSource, $ConfigSource)) {
        if (-not (Test-Path -LiteralPath $src -PathType Leaf)) {
            throw "Required file not found: $src"
        }
    }

    # Ensure destination folders
    Ensure-Folder "C:\Users\Public\OpcenterRDnL\DynamicLibraries"
    Ensure-Folder $ApprovedFolder
    Ensure-Folder "C:\Users\Public\OpcenterRDnL"
    Ensure-Folder $OpcenterExcrFolder

    # COPY DLL to Approved
    $dllName = Split-Path -Leaf $DllSource
    $dllDest = Join-Path $ApprovedFolder $dllName
    Write-Host "Copying $dllName -> $ApprovedFolder"
    Copy-Item -LiteralPath $DllSource -Destination $dllDest -Force

    # COPY config.txt to OpcenterEXCR
    $cfgName = Split-Path -Leaf $ConfigSource
    $cfgDest = Join-Path $OpcenterExcrFolder $cfgName
    Write-Host "Copying $cfgName -> $OpcenterExcrFolder"
    Copy-Item -LiteralPath $ConfigSource -Destination $cfgDest -Force

    Write-Host "✅ Copy deployment completed successfully." -ForegroundColor Green
    Write-Host "  Approved: $dllDest"
    Write-Host "  Config:   $cfgDest"
}
catch {
    Write-Error "❌ Error: $($_.Exception.Message)"
    exit 1
}
finally {
    Stop-Transcript | Out-Null
}
